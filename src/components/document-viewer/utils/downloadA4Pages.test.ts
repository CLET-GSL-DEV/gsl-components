function tinyJpegDataUrl() {
  let binary = "";
  for (const byte of TINY_JPEG) binary += String.fromCharCode(byte);
  return `data:image/jpeg;base64,${btoa(binary)}`;
}

describe("ensureXhtmlNamespace", () => {
  it("does not duplicate an existing xmlns", () => {
    const input =
      '<div xmlns="http://www.w3.org/1999/xhtml" class="page">Hi</div>';
    expect(ensureXhtmlNamespace(input)).toBe(input);
  });

  it("adds xmlns when missing", () => {
    expect(ensureXhtmlNamespace('<div class="page">Hi</div>')).toBe(
      '<div xmlns="http://www.w3.org/1999/xhtml" class="page">Hi</div>',
    );
  });
});

describe("bytesToBase64", () => {
  it("encodes bytes", () => {
    expect(bytesToBase64(Uint8Array.from([72, 105]))).toBe(btoa("Hi"));
  });
});

describe("buildPdfFromJpegPages", () => {
  it("builds a multi-page PDF byte stream", () => {
    const pdf = buildPdfFromJpegPages([
      { data: TINY_JPEG, width: 1, height: 1 },
      { data: TINY_JPEG, width: 1, height: 1 },
    ]);
    const text = new TextDecoder("latin1").decode(pdf);
    expect(text.startsWith("%PDF-1.4")).toBe(true);
    expect(text).toContain("/Count 2");
    expect(text).toContain("/Type /Page");
    expect(text).toContain("%%EOF");
  });
});

describe("downloadA4Pages", () => {
  afterEach(() => {
    vi.restoreAllMocks();
    vi.unstubAllGlobals();
    resetEmbeddedFontCssCache();
    document.body.innerHTML = "";
  });

  it("downloads a .pdf blob built from page nodes", async () => {
    const root = document.createElement("div");
    root.innerHTML = `
      <div class="clet-document-viewer__page" style="width:120px;height:160px"><p>Page one</p></div>
      <div class="clet-document-viewer__page" style="width:120px;height:160px"><p>Page two</p></div>
    `;
    document.body.appendChild(root);

    Object.defineProperty(document, "fonts", {
      configurable: true,
      value: { ready: Promise.resolve() },
    });

    class MockImage {
      onload: (() => void) | null = null;
      onerror: (() => void) | null = null;
      width = 120;
      height = 160;
      set src(_value: string) {
        queueMicrotask(() => this.onload?.());
      }
    }
    vi.stubGlobal("Image", MockImage);

    const ctx = {
      fillStyle: "",
      fillRect: vi.fn(),
      drawImage: vi.fn(),
    };
    vi.spyOn(HTMLCanvasElement.prototype, "getContext").mockReturnValue(
      ctx as unknown as CanvasRenderingContext2D,
    );
    vi.spyOn(HTMLCanvasElement.prototype, "toDataURL").mockReturnValue(
      tinyJpegDataUrl(),
    );

    const createObjectURL = vi
      .spyOn(URL, "createObjectURL")
      .mockReturnValue("blob:mock-pdf");
    const revokeObjectURL = vi
      .spyOn(URL, "revokeObjectURL")
      .mockImplementation(() => {});

    const click = vi.fn();
    const originalCreateElement = document.createElement.bind(document);
    vi.spyOn(document, "createElement").mockImplementation(
      (tagName: string, options?: ElementCreationOptions) => {
        const el = originalCreateElement(tagName, options);
        if (tagName.toLowerCase() === "a") {
          el.click = click;
        }
        return el;
      },
    );

    await downloadA4Pages(root, "INV-2026-0142.html");

    const pdfCall = createObjectURL.mock.calls.find(
      (call) => call[0] instanceof Blob && (call[0] as Blob).type === "application/pdf",
    );
    expect(pdfCall).toBeTruthy();
    const blob = pdfCall?.[0] as Blob;
    expect(blob.type).toBe("application/pdf");
    expect(click).toHaveBeenCalled();
    expect(revokeObjectURL).toHaveBeenCalledWith("blob:mock-pdf");
  });
});
